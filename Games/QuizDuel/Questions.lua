-- Lookups: ns.CATEGORY[key], ns.QUESTION[id] = { id, text, answers = { right, wrong... } }
ns.CATEGORY = {}
ns.QUESTION = {}
for _, category in ipairs(ns.CATEGORIES) do
	ns.CATEGORY[category.key] = category
	for i, entry in ipairs(category.questions) do
		local question = { id = category.key .. i, text = entry[1], answers = { entry[2], entry[3], entry[4], entry[5] } }
		category.questions[i] = question
		ns.QUESTION[question.id] = question
	end
end
